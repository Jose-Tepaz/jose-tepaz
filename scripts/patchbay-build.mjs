// Writes public/patchbay.svg, the patch bay's static art (everything that never moves or changes
// with the lamp) with its stylesheet inline, and components/iso/patchbay/rest.mjs, the rest pose of
// the parts that do move, so PatchBay renders without importing any geometry code.
// Run after any change to components/iso/patchbay: node scripts/patchbay-build.mjs
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { H, W } from '../components/iso/patchbay/layout.mjs'
import { CORDS } from '../components/iso/patchbay/model.mjs'
import { buildStatic } from '../components/iso/patchbay/static.mjs'
import { buildUnit } from '../components/iso/patchbay/unit.mjs'

const here = (path) => fileURLToPath(new URL(path, import.meta.url))
const css = readFileSync(here('../components/iso/patchbay/patchbay.css'), 'utf8')
  .split('\n')
  .filter((line) => !/^\.pb-(box|art)/.test(line))
  .join('\n')
const { art, overlay } = buildStatic()
const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${W} ${H}" class="pb"><style>${css}</style>${art}</svg>\n`
writeFileSync(here('../public/patchbay.svg'), svg)
console.log(`public/patchbay.svg · ${(svg.length / 1024).toFixed(0)} KB`)

const units = Array.from({ length: CORDS }, (_, i) => buildUnit(null, i, 0))
writeFileSync(
  here('../components/iso/patchbay/rest.mjs'),
  `// Generated by scripts/patchbay-build.mjs: do not edit.\nexport const SIZE = [${W}, ${H}]\nexport const OVERLAY = ${JSON.stringify(overlay)}\nexport const UNITS = ${JSON.stringify(units)}\n`,
)
console.log(
  `rest.mjs · overlay ${(overlay.length / 1024).toFixed(0)} KB, units ${units.map((u) => (u.length / 1024).toFixed(0)).join('+')} KB`,
)
